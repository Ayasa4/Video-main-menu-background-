# make_pack.ps1
# Prepares videos for the Video Main Menu pack:
#   - copies every video from the "source" folder into the pack folder using an ASCII-safe file name
#     (the game cannot read file names with Japanese, Thai or other non-ASCII characters, or spaces)
#   - next to every renamed video it writes "<file>.title.txt" holding the original name, so the in-game
#     list still shows it. Every video has its own title file, so several pack addons never clash
#     (when two addons contain a file with the same name, the game can only read one of them).
#
# Usage:   make_pack.bat
#            source = .\source
#            dest   = .\videomenu_pack\data_static\videomenu_pack
#          make_pack.bat "<dest folder>" "<source folder>"

param(
    [string]$Dest   = (Join-Path $PSScriptRoot 'videomenu_pack\data_static\videomenu_pack'),
    [string]$Source = (Join-Path $PSScriptRoot 'source')
)
$ErrorActionPreference = 'Stop'

if (-not (Test-Path -LiteralPath $Source)) {
    New-Item -ItemType Directory -Path $Source | Out-Null
    Write-Host "Created: $Source"
    Write-Host 'Put your videos there (any file name; .webm, or .txt files that contain WebM video), then run this again.'
    exit 0
}

$videos = @(Get-ChildItem -LiteralPath $Source -File | Where-Object {
    ($_.Extension -ieq '.webm' -or $_.Extension -ieq '.txt') -and
    ($_.Name -ine 'README.txt') -and ($_.Name -notlike 'titles*.txt') -and ($_.Name -notlike '*.title.txt')
} | Sort-Object Name)

if ($videos.Count -eq 0) {
    Write-Host "No .webm / .txt videos found in: $Source"
    exit 0
}

New-Item -ItemType Directory -Path $Dest -Force | Out-Null

$utf8   = New-Object System.Text.UTF8Encoding($false)
$sha    = [System.Security.Cryptography.SHA1]::Create()
$seen   = @{}
$made   = @{}
$titled = @{}

foreach ($f in $videos) {
    $base = [System.IO.Path]::GetFileNameWithoutExtension($f.Name)
    $key  = $base.ToLowerInvariant()
    if ($seen.ContainsKey($key)) { Write-Host "  skip duplicate: $($f.Name)"; continue }
    $seen[$key] = $true

    if ($base -cmatch '^[A-Za-z0-9_-]+$') {
        $out = $base
    } else {
        $hash = [System.BitConverter]::ToString($sha.ComputeHash([System.Text.Encoding]::UTF8.GetBytes($base)))
        $out  = 'vm_' + $hash.Replace('-', '').Substring(0, 8).ToLowerInvariant()

        $titleName = $out + '.title.txt'
        [System.IO.File]::WriteAllText((Join-Path $Dest $titleName), $base, $utf8)
        $titled[$titleName.ToLowerInvariant()] = $true
    }

    $name = $out + '.txt'
    $made[$name.ToLowerInvariant()] = $true
    [System.IO.File]::Copy($f.FullName, (Join-Path $Dest $name), $true)
    Write-Host ("  {0}  <-  {1}" -f $name, $f.Name)
}

# remove generated files from earlier runs that are no longer in the source folder
Get-ChildItem -LiteralPath $Dest -File | Where-Object {
    ($_.Name -match '^vm_[0-9a-f]{8}\.txt$' -and -not $made.ContainsKey($_.Name.ToLowerInvariant())) -or
    ($_.Name -match '^vm_[0-9a-f]{8}\.title\.txt$' -and -not $titled.ContainsKey($_.Name.ToLowerInvariant()))
} | ForEach-Object {
    [System.IO.File]::Delete($_.FullName)
    Write-Host "  removed old: $($_.Name)"
}

# older versions of this script wrote a shared titles.txt; it is no longer used, so delete it
# (only when it was generated by this script)
Get-ChildItem -LiteralPath $Dest -File -Filter 'titles*.txt' | ForEach-Object {
    $first = Get-Content -LiteralPath $_.FullName -TotalCount 1 -Encoding UTF8
    if ($first -like '# generated by make_pack.ps1*') {
        [System.IO.File]::Delete($_.FullName)
        Write-Host "  removed old shared title file: $($_.Name)"
    }
}

$stray = @(Get-ChildItem -LiteralPath $Dest -File | Where-Object {
    ($_.Extension -ieq '.txt' -or $_.Extension -ieq '.webm') -and
    ($_.Name -ine 'README.txt') -and ($_.Name -notlike 'titles*.txt') -and ($_.Name -notlike '*.title.txt') -and
    -not $made.ContainsKey($_.Name.ToLowerInvariant())
})
if ($stray.Count -gt 0) {
    Write-Host ''
    Write-Host 'WARNING: these files in the destination were not made by this script.'
    Write-Host 'If their names contain non-ASCII characters (Japanese etc.) the game cannot read them.'
    Write-Host 'Move them into the source folder and run this script again:'
    foreach ($s in $stray) { Write-Host "  $($s.Name)" }
}

Write-Host ''
Write-Host ("Done: {0} video(s) -> {1}" -f $made.Count, $Dest)
